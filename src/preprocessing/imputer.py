"""
imputer.py
----------
Context-Aware Missing Value Imputation with Biological Guardrails Enforcement.

This module executes the imputation actions generated by the Intelligent Decision
Engine. Features with discovered dependencies are imputed using ContextAwareKNN
(restricted to their specific predictor graph edges). Imputed values are subsequently
audited and bounded by the LOINC Biological Guardrails.
"""

import json
import logging
import os
import re
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
from sklearn.impute import KNNImputer

from src.models.dataset import Dataset


class ContextAwareImputer:
    """
    Executes context-aware missing value imputation and enforces biological guardrails.
    """

    # Common medical feature name alias mapping for LOINC lookup
    ALIAS_MAP = {
        "bp": "blood pressure",
        "sbp": "blood pressure systolic",
        "dbp": "blood pressure diastolic",
        "blood_pressure": "blood pressure systolic & diastolic",
        "fbs": "glucose",
        "bld_sug": "glucose",
        "glucose": "glucose",
        "chol": "cholesterol",
        "cholesterol": "cholesterol",
        "hgb": "hemoglobin",
        "hb": "hemoglobin",
        "plt": "platelet",
        "platelet": "platelet",
        "rbc": "erythrocyte",
        "wbc": "leukocyte",
        "tlc": "leukocyte",
        "mcv": "erythrocyte mean corpuscular volume",
        "mch": "erythrocyte mean corpuscular hemoglobin",
        "mchc": "erythrocyte mean corpuscular hemoglobin concentration",
        "rdw": "erythrocyte distribution width",
        "pcv": "hematocrit",
        "bmi": "body mass index",
        "weight": "body weight",
        "height": "body height",
        "age": "age",
    }

    def __init__(
        self,
        guardrails_path: str = "datasets/biological_guardrails.json",
        n_neighbors: int = 5,
    ):
        self.logger = logging.getLogger("IRAP_ContextAwareImputer")
        self.guardrails_path = guardrails_path
        self.n_neighbors = n_neighbors
        self.guardrails: Dict[str, Any] = {}
        self._load_guardrails()

    def _load_guardrails(self) -> None:
        """Loads the biological guardrails JSON if available."""
        if os.path.exists(self.guardrails_path):
            try:
                with open(self.guardrails_path, "r", encoding="utf-8") as f:
                    self.guardrails = json.load(f)
                self.logger.info(f"Loaded {len(self.guardrails)} biological guardrail rules.")
            except Exception as e:
                self.logger.warning(f"Could not load biological guardrails from {self.guardrails_path}: {e}")
        else:
            self.logger.warning(f"Biological guardrails file not found at {self.guardrails_path}.")

    def find_guardrail(self, col_name: str) -> Optional[Dict[str, Any]]:
        """
        Finds a matching biological guardrail entry for a given column name.
        Uses exact match, alias resolution, and substring search.
        """
        clean_col = re.sub(r"[^a-zA-Z0-9\s]", " ", col_name).strip().lower()

        # 1. Direct match in guardrails dictionary
        if clean_col in self.guardrails:
            return self.guardrails[clean_col]

        # 2. Match through alias dictionary
        for alias, mapped_term in self.ALIAS_MAP.items():
            if alias == clean_col or alias in clean_col.split():
                if mapped_term in self.guardrails:
                    return self.guardrails[mapped_term]
                # Look for mapped term as substring in guardrails
                for k, v in self.guardrails.items():
                    if mapped_term in k and (v.get("min_value") is not None or v.get("max_value") is not None):
                        return v

        # 3. Substring match
        for k, v in self.guardrails.items():
            if clean_col in k and (v.get("min_value") is not None or v.get("max_value") is not None):
                return v

        # 4. Built-in physical safety heuristic for common biological terms
        non_negative_keywords = [
            "age", "bmi", "pressure", "glucose", "cholesterol", "insulin",
            "count", "rate", "weight", "height", "rbc", "wbc", "hgb",
            "plt", "mcv", "mch", "mchc", "rdw", "pcv", "tlc"
        ]
        if any(keyword in clean_col for keyword in non_negative_keywords):
            return {"min_value": 0.0, "max_value": None, "source": "heuristic_safety_net"}

        return None

    def apply_guardrails(self, series: pd.Series, col_name: str) -> Tuple[pd.Series, int]:
        """
        Applies physical bounds to imputed numeric values based on guardrails.
        Returns the clamped series and number of violations corrected.
        """
        if not pd.api.types.is_numeric_dtype(series):
            return series, 0

        guardrail = self.find_guardrail(col_name)
        if not guardrail:
            return series, 0

        min_val = guardrail.get("min_value")
        max_val = guardrail.get("max_value")
        violations = 0

        clamped = series.copy()
        if min_val is not None:
            violation_mask = clamped < min_val
            count = int(violation_mask.sum())
            if count > 0:
                violations += count
                clamped[violation_mask] = min_val
                self.logger.info(
                    f"Guardrail Enforcement on '{col_name}': Clamped {count} value(s) "
                    f"below physical minimum {min_val}."
                )

        if max_val is not None:
            violation_mask = clamped > max_val
            count = int(violation_mask.sum())
            if count > 0:
                violations += count
                clamped[violation_mask] = max_val
                self.logger.info(
                    f"Guardrail Enforcement on '{col_name}': Clamped {count} value(s) "
                    f"above physical maximum {max_val}."
                )

        return clamped, violations

    def impute(self, dataset: Dataset) -> Dataset:
        """
        Executes the imputation plan on dataset.dataframe.
        """
        self.logger.info("Starting Context-Aware Imputation...")

        if not dataset.has_data():
            self.logger.warning("No data found to impute.")
            return dataset

        df = dataset.dataframe.copy()
        total_imputations = 0
        total_guardrail_interventions = 0
        dropped_columns = []

        # Parse preprocessing plan
        plan = dataset.preprocessing_plan or []

        for feature_plan in plan:
            col_name = feature_plan["feature"]
            if col_name not in df.columns:
                continue

            for action in feature_plan.get("actions", []):
                if action.get("step") != "imputation":
                    continue

                method = action.get("method")
                missing_mask = df[col_name].isna()
                missing_count = int(missing_mask.sum())

                if method == "DropColumn":
                    dropped_columns.append(col_name)
                    df.drop(columns=[col_name], inplace=True)
                    self.logger.info(f"Dropped column '{col_name}' ({action.get('reason')}).")
                    dataset.preprocessing_history.append(f"Dropped column '{col_name}'.")
                    break

                if missing_count == 0:
                    continue

                self.logger.info(
                    f"Imputing {missing_count} missing values in '{col_name}' using {method}..."
                )

                if method == "ContextAwareKNN":
                    predictors = action.get("predictors", [])
                    # Filter valid numeric/factorizable predictors present in df
                    available_predictors = [p for p in predictors if p in df.columns and p != col_name]

                    if not available_predictors:
                        # Fallback to all other columns if specific predictors are not present
                        available_predictors = [c for c in df.columns if c != col_name]

                    # Prepare subset matrix for KNN
                    subset_cols = available_predictors + [col_name]
                    temp_df = df[subset_cols].copy()

                    # Convert any non-numeric columns in subset to numeric codes (keeping NaNs)
                    for c in subset_cols:
                        if not pd.api.types.is_numeric_dtype(temp_df[c]):
                            codes, _ = pd.factorize(temp_df[c])
                            c_float = codes.astype(float)
                            c_float[codes == -1] = np.nan
                            temp_df[c] = c_float

                    # Execute KNN Imputer
                    k = min(self.n_neighbors, max(1, len(temp_df) - 1))
                    knn = KNNImputer(n_neighbors=k, weights="distance")
                    imputed_subset = knn.fit_transform(temp_df)
                    imputed_series = pd.Series(imputed_subset[:, -1], index=df.index)

                    # If original column was categorical/integer, round or decode
                    if pd.api.types.is_integer_dtype(df[col_name]):
                        imputed_series = imputed_series.round().astype(df[col_name].dtype)
                    elif not pd.api.types.is_numeric_dtype(df[col_name]):
                        # If original was object/string, nearest category
                        unique_cats = df[col_name].dropna().unique()
                        if len(unique_cats) > 0:
                            indices = imputed_series.round().clip(0, len(unique_cats) - 1).astype(int)
                            imputed_series = pd.Series(unique_cats[indices], index=df.index)

                    # Update missing values
                    df.loc[missing_mask, col_name] = imputed_series[missing_mask]
                    total_imputations += missing_count

                elif method == "MedianImputer":
                    median_val = df[col_name].median()
                    df[col_name] = df[col_name].fillna(median_val)
                    total_imputations += missing_count

                elif method == "ModeImputer":
                    mode_val = df[col_name].mode()
                    fill_val = mode_val.iloc[0] if not mode_val.empty else "Unknown"
                    df[col_name] = df[col_name].fillna(fill_val)
                    total_imputations += missing_count

                # Apply Biological Guardrails to newly imputed values
                if col_name in df.columns and pd.api.types.is_numeric_dtype(df[col_name]):
                    df[col_name], violations = self.apply_guardrails(df[col_name], col_name)
                    total_guardrail_interventions += violations
                    if violations > 0:
                        profile = dataset.feature_profiles.get(col_name)
                        if profile:
                            profile.validation_rules.append(
                                f"Biological Guardrail clamped {violations} out-of-bounds values."
                            )

                dataset.preprocessing_history.append(
                    f"Imputed '{col_name}' ({missing_count} values) via {method}."
                )

        # Update dataset dataframe
        dataset.dataframe = df
        dataset.pipeline_history.append(
            f"Context-Aware Imputation completed: {total_imputations} missing values filled across "
            f"features. {total_guardrail_interventions} biological guardrail bounds enforced."
        )
        dataset.update_modified_time()

        self.logger.info(
            f"Context-Aware Imputation finished. Total imputed: {total_imputations}, "
            f"Guardrail interventions: {total_guardrail_interventions}, Dropped columns: {dropped_columns}"
        )

        return dataset

